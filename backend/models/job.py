"""Pydantic v2 schemas for Jobs, Editorial Clips, EDL, Storyboard, and Metrics."""

from __future__ import annotations

from datetime import datetime, timezone
from typing import Any, Literal, Optional

from pydantic import BaseModel, Field

from backend.models.profile import AspectRatio, CustomImage, ImageDisplayMode, MediaProviderId


ClipType = Literal["short_cliffhanger", "short_conclusive", "medium", "long"]
ExecutionMode = Literal["auto", "semi_auto", "review_before_render"]
JobStatus = Literal[
    "queued",
    "running",
    "awaiting_topic_selection",
    "awaiting_review",
    "completed",
    "failed",
    "cancelled",
]
PhaseName = Literal[
    "transcription",
    "editorial",
    "audio_edit",
    "visual_direction",
    "rendering",
]
EnergyLevel = Literal["baja", "media", "alta"]


class SentenceSegment(BaseModel):
    """Indexed sentence/clause from Pass 1 draft transcription."""

    id: str  # e.g. "S0001"
    start: float
    end: float
    text: str
    speaker: Optional[str] = None


class WordTimestamp(BaseModel):
    """Word-level timestamp from Pass 2 precision transcription (or mapped EDL timeline)."""

    word: str
    start: float
    end: float
    probability: float = 1.0
    censored: bool = False
    speaker: Optional[str] = None


class NarrativeSpan(BaseModel):
    """A single real audio span inside a non-linear or contiguous narrative clip."""

    start_sentence_id: str
    end_sentence_id: str
    orig_start: float
    orig_end: float
    role: Literal["cold_open_hook", "context_intro", "question", "core", "payoff"] = "core"


class EDLSegment(BaseModel):
    """A kept audio slice mapping original clip timeline to clean output timeline."""

    index: int
    orig_start: float
    orig_end: float
    out_start: float
    out_end: float
    crossfade_in_sec: float = 0.0
    crossfade_curve: Literal["tri", "qsin"] = "tri"


class EDLPlan(BaseModel):
    """Complete Edit Decision List for one clip."""

    clip_id: str
    orig_clip_start: float
    orig_clip_end: float
    orig_duration: float
    edited_duration: float
    silences_removed_count: int = 0
    silences_removed_sec: float = 0.0
    music_gaps_removed_count: int = 0
    music_gaps_removed_sec: float = 0.0
    censored_hits_count: int = 0
    censored_terms_matched: list[str] = Field(default_factory=list)
    segments: list[EDLSegment] = Field(default_factory=list)


class ChapterMark(BaseModel):
    """Chapter timestamp for medium/long videos."""

    title: str
    sentence_id: Optional[str] = None
    orig_time_sec: float = 0.0
    edited_time_sec: float = 0.0


class ClipMetadata(BaseModel):
    """Ready-to-publish metadata pack generated by the editorial engine."""

    titles: list[str] = Field(default_factory=list)
    description: str = ""
    hashtags: list[str] = Field(default_factory=list)
    thumbnail_text: str = ""
    cliffhanger_question: str = ""
    hook_text: str = ""
    chapters: list[ChapterMark] = Field(default_factory=list)


class StoryboardShot(BaseModel):
    """Single visual shot in the edited clip timeline."""

    id: str
    start: float
    end: float
    source_type: Literal[
        "custom_image",
        "stock_video",
        "stock_photo",
        "archive_media",
        "title_card",
        "quote_card",
    ]
    custom_image_id: Optional[str] = None
    custom_image_filename: Optional[str] = None
    display_mode: ImageDisplayMode = "fullscreen_zoom"
    stock_query: str = ""
    stock_asset_id: Optional[str] = None
    local_media_path: Optional[str] = None
    card_title: str = ""
    card_subtitle: str = ""
    reason: str = ""


class StoryboardPlan(BaseModel):
    """Full visual storyboard covering [0, clip_duration]."""

    clip_id: str
    aspect_ratio: AspectRatio
    duration: float
    shots: list[StoryboardShot] = Field(default_factory=list)


class EditableSubtitleLine(BaseModel):
    """Editable subtitle phrase line for review mode."""

    index: int
    start: float
    end: float
    text: str
    speaker: Optional[str] = None


class ClipCandidate(BaseModel):
    """Selected clip progressing through EDL, storyboard, review, and render."""

    id: str
    candidate_id: str = ""
    original_title: str = ""
    user_rescued: bool = False
    clip_type: ClipType
    aspect_ratio: AspectRatio
    score: int = Field(ge=0, le=100)
    slug: str
    summary: str = ""
    hook_reason: str = ""
    enabled: bool = True

    start_sentence_id: str
    end_sentence_id: str
    orig_start: float
    orig_end: float
    estimated_post_cut_sec: float = 0.0
    narrative_archetype: str = "mini_historia"
    angle_id: str = ""
    angle_theme: str = ""
    narrative_spans: list[NarrativeSpan] = Field(default_factory=list)
    speakers_detected: list[str] = Field(default_factory=list)
    speaker_color_map: dict[str, str] = Field(default_factory=dict)
    visual_hook_enabled: Optional[bool] = None
    visual_hook_end_sec: float = 0.0
    visual_hook_spoken_text: str = ""
    visual_credits_audit: list[dict[str, Any]] = Field(default_factory=list)
    license_warnings: list[str] = Field(default_factory=list)
    license_manifest_path: Optional[str] = None
    standalone_packaging: dict[str, Any] = Field(default_factory=dict)

    # Intro / Outro AI Curtains
    intro_curtain_enabled: Optional[bool] = None
    intro_curtain_text: str = ""
    intro_curtain_phrases: list[str] = Field(default_factory=list)
    intro_curtain_badge: str = ""
    intro_curtain_audio_path: Optional[str] = None
    intro_curtain_duration_sec: float = 0.0
    intro_curtain_word_timings: list[dict[str, Any]] = Field(default_factory=list)

    outro_curtain_enabled: Optional[bool] = None
    outro_curtain_audio_path: Optional[str] = None
    outro_curtain_duration_sec: float = 0.0

    # Populated during Phase 3 (Audio & EDL)
    precision_words: list[WordTimestamp] = Field(default_factory=list)
    mapped_words: list[WordTimestamp] = Field(default_factory=list)
    edl: Optional[EDLPlan] = None
    clean_wav_path: Optional[str] = None
    preview_audio_path: Optional[str] = None

    # Populated during Phase 4 (Visuals & Subtitles)
    metadata: ClipMetadata = Field(default_factory=ClipMetadata)
    storyboard: Optional[StoryboardPlan] = None
    subtitle_lines: list[EditableSubtitleLine] = Field(default_factory=list)
    ass_path: Optional[str] = None

    # Populated during Phase 5 (Render)
    rendered_video_path: Optional[str] = None
    thumbnail_path: Optional[str] = None
    output_filename: Optional[str] = None
    render_completed: bool = False


class JobQuotasOverride(BaseModel):
    """Per-job overrides for clip quantities and execution mode."""

    shorts_cliffhanger_count: Optional[int] = Field(default=None, ge=0, le=30)
    shorts_conclusive_count: Optional[int] = Field(default=None, ge=0, le=30)
    medium_videos_count: Optional[int] = Field(default=None, ge=0, le=10)
    long_videos_count: Optional[int] = Field(default=None, ge=0, le=10)
    auto_mode: bool = True


class ModelUsageRecord(BaseModel):
    """Token and cost breakdown for a single OpenRouter model."""

    model: str
    calls: int = 0
    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0
    cost_usd: float = 0.0
    total_latency_sec: float = 0.0


class CostMetrics(BaseModel):
    """Cumulative OpenRouter token and cost tracking for a job."""

    total_calls: int = 0
    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0
    cost_usd: float = 0.0
    cost_eur: float = 0.0
    usd_to_eur_rate: float = 0.92
    by_model: dict[str, ModelUsageRecord] = Field(default_factory=dict)


class PhaseProgress(BaseModel):
    """Status and percentage of each of the 5 pipeline phases."""

    phase: PhaseName
    label: str
    status: Literal["pending", "running", "completed", "skipped", "failed"] = "pending"
    progress_pct: float = 0.0
    detail: str = ""
    started_at: Optional[str] = None
    completed_at: Optional[str] = None
    duration_sec: Optional[float] = None
    eta_sec: Optional[float] = None
    substep: str = ""
    items_done: int = 0
    items_total: int = 0


class JobState(BaseModel):
    """Full persisted job state saved as checkpoint JSON in processing/<job_id>/job.json."""

    job_id: str
    profile_id: str
    episode_name: str
    source_audio_path: str
    audio_duration_sec: float = 0.0
    detected_language: str = "es"
    auto_mode: bool = True
    execution_mode: ExecutionMode = "auto"
    pause_before_render: bool = False
    topics_confirmed: bool = False

    requested_shorts_cliffhanger: int = 3
    requested_shorts_conclusive: int = 3
    requested_medium: int = 1
    requested_long: int = 1

    episode_images: list[CustomImage] = Field(default_factory=list)
    allowed_media_providers: Optional[list[MediaProviderId]] = None
    visual_hook_enabled: Optional[bool] = None
    visual_hook_style: Optional[str] = None
    intro_curtain_enabled: Optional[bool] = None
    outro_curtain_enabled: Optional[bool] = None
    episode_glossary: dict[str, str] = Field(default_factory=dict)
    visual_bible: dict[str, Any] = Field(default_factory=dict)
    license_warnings: list[str] = Field(default_factory=list)

    status: JobStatus = "queued"
    current_phase: PhaseName = "transcription"
    active_step: str = ""
    heartbeat_at: str = ""
    overall_progress_pct: float = 0.0
    phases: list[PhaseProgress] = Field(default_factory=list)
    warnings: list[str] = Field(default_factory=list)
    error_message: Optional[str] = None

    clips: list[ClipCandidate] = Field(default_factory=list)
    editorial_blocks: list[dict[str, Any]] = Field(default_factory=list)
    candidate_pool: list[ClipCandidate] = Field(default_factory=list)
    rejected_candidates: list[dict[str, Any]] = Field(default_factory=list)
    live_metrics: dict[str, Any] = Field(default_factory=dict)
    output_dir: Optional[str] = None
    output_dir_override: Optional[str] = None
    save_analytics_report: bool = False
    cost: CostMetrics = Field(default_factory=CostMetrics)
    logs: list[dict[str, Any]] = Field(default_factory=list)

    created_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
    updated_at: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())
